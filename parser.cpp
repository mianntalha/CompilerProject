
#include <iostream>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>
#include <cctype>
#include <cstdlib>

using namespace std;

struct Token
{
    string category;
    string lexeme;
    int lineNumber;
};

vector<Token> tokenList;
size_t tokenIndex = 0;
int finalLine = 1;

// Convert escaped characters into their actual representation
string decodeLexeme(const string& value)
{
    string decoded;

    for (size_t i = 0; i < value.length(); ++i)
    {
        if (value[i] == '\\' && i + 1 < value.length())
        {
            char next = value[++i];

            switch (next)
            {
                case 't': decoded += '\t'; break;
                case 'n': decoded += '\n'; break;
                case 'r': decoded += '\r'; break;
                default:  decoded += next; break;
            }
        }
        else
        {
            decoded += value[i];
        }
    }

    return decoded;
}

// Read tokens generated by the lexical analyzer
bool readTokenFile(const string& path)
{
    ifstream input(path.c_str());

    if (!input.is_open())
    {
        cerr << "Error: unable to open token file '" << path << "'.\n";
        return false;
    }

    string record;
    int recordCount = 0;

    while (getline(input, record))
    {
        ++recordCount;

        size_t separatorOne = record.find('\t');
        size_t separatorTwo = string::npos;

        if (separatorOne != string::npos)
            separatorTwo = record.find('\t', separatorOne + 1);

        if (separatorOne == string::npos ||
            separatorTwo == string::npos)
        {
            cerr << "Error: invalid token format on token-file line "
                 << recordCount
                 << ". Expected TYPE<TAB>LINE<TAB>LEXEME.\n";
            return false;
        }

        string lineValue = record.substr(
            separatorOne + 1,
            separatorTwo - separatorOne - 1
        );

        int sourceLine = 0;
        bool numericLine = !lineValue.empty();

        for (char ch : lineValue)
        {
            if (!isdigit(static_cast<unsigned char>(ch)))
            {
                numericLine = false;
                break;
            }

            sourceLine = sourceLine * 10 + (ch - '0');
        }

        if (!numericLine || sourceLine < 1)
        {
            cerr << "Error: invalid line number on token-file line "
                 << recordCount << ".\n";
            return false;
        }

        Token newToken;
        newToken.category = record.substr(0, separatorOne);
        newToken.lineNumber = sourceLine;
        newToken.lexeme = decodeLexeme(
            record.substr(separatorTwo + 1)
        );

        tokenList.push_back(newToken);
        finalLine = sourceLine;
    }

    if (input.bad())
    {
        cerr << "Error: unable to read token file '" << path << "'.\n";
        return false;
    }

    return true;
}

// Return the next token without consuming it
Token* currentToken()
{
    if (tokenIndex < tokenList.size())
        return &tokenList[tokenIndex];

    return NULL;
}

bool hasLexeme(const string& value)
{
    Token* token = currentToken();
    return token != NULL && token->lexeme == value;
}

bool isIdentifier()
{
    Token* token = currentToken();

    return token != NULL &&
           (token->category == "IDENTIFIER" ||
            token->lexeme == "main");
}

// Consume a token if its lexeme matches
bool matchToken(const string& value)
{
    if (!hasLexeme(value))
        return false;

    ++tokenIndex;
    return true;
}

// Display syntax errors with their source line
void reportSyntaxError(const string& reason)
{
    Token* token = currentToken();

    int line = (token == NULL)
                   ? finalLine
                   : token->lineNumber;

    cerr << "Syntax error on line " << line
         << ": " << reason << ".\n";

    exit(1);
}

void requireToken(const string& value)
{
    if (!matchToken(value))
        reportSyntaxError("expected '" + value + "'");
}

void requireIdentifier()
{
    if (!isIdentifier())
        reportSyntaxError("expected an identifier");

    ++tokenIndex;
}

bool isType()
{
    return hasLexeme("int32") ||
           hasLexeme("float32") ||
           hasLexeme("struct");
}

// Parse primitive and structure types
void readType()
{
    if (matchToken("int32") || matchToken("float32"))
        return;

    if (matchToken("struct"))
    {
        requireIdentifier();
        return;
    }

    reportSyntaxError("expected a type name");
}

void expression();
void codeBlock();

void functionArguments()
{
    if (!hasLexeme(")"))
    {
        expression();

        while (matchToken(","))
            expression();
    }

    requireToken(")");
}

// Parse literals, variables, function calls and grouped expressions
void primaryExpression()
{
    Token* token = currentToken();

    if (token == NULL)
        reportSyntaxError("expected an expression");

    if (token->category == "INTEGER" ||
        token->category == "FLOAT" ||
        token->category == "STRING")
    {
        ++tokenIndex;
        return;
    }

    if (isIdentifier())
    {
        ++tokenIndex;

        if (matchToken("("))
        {
            functionArguments();
            return;
        }

        while (matchToken("."))
            requireIdentifier();

        return;
    }

    if (matchToken("("))
    {
        expression();
        requireToken(")");
        return;
    }

    reportSyntaxError(
        "expected a number, string, identifier, or '('"
    );
}

// Unary operators
void unaryExpression()
{
    if (matchToken("!") ||
        matchToken("-") ||
        matchToken("+"))
    {
        unaryExpression();
        return;
    }

    primaryExpression();
}

// Multiplication, division and modulus
void multiplicativeExpression()
{
    unaryExpression();

    while (hasLexeme("*") ||
           hasLexeme("/") ||
           hasLexeme("%"))
    {
        ++tokenIndex;
        unaryExpression();
    }
}

// Addition and subtraction
void additiveExpression()
{
    multiplicativeExpression();

    while (hasLexeme("+") || hasLexeme("-"))
    {
        ++tokenIndex;
        multiplicativeExpression();
    }
}

// Relational operators
void relationalExpression()
{
    additiveExpression();

    while (hasLexeme("<") ||
           hasLexeme(">") ||
           hasLexeme("<=") ||
           hasLexeme(">="))
    {
        ++tokenIndex;
        additiveExpression();
    }
}

// Equality operators
void equalityExpression()
{
    relationalExpression();

    while (hasLexeme("==") || hasLexeme("!="))
    {
        ++tokenIndex;
        relationalExpression();
    }
}

// Logical AND
void andExpression()
{
    equalityExpression();

    while (matchToken("&&"))
        equalityExpression();
}

// Complete expression including logical OR
void expression()
{
    andExpression();

    while (matchToken("||"))
        andExpression();
}

// Variable declarations
void variableDeclaration()
{
    readType();
    requireIdentifier();

    while (true)
    {
        if (matchToken("=") || matchToken("medalo"))
            expression();

        if (!matchToken(","))
            break;

        requireIdentifier();
    }

    requireToken(";");
}

// Structure declarations
void structureDeclaration()
{
    requireToken("struct");
    requireIdentifier();
    requireToken("shru");

    while (!hasLexeme("khatam"))
    {
        if (currentToken() == NULL)
            reportSyntaxError(
                "expected 'khatam' to end the structure"
            );

        variableDeclaration();
    }

    requireToken("khatam");
    requireToken(";");
}

// Function parameters
void parameterList()
{
    if (!hasLexeme(")"))
    {
        readType();
        requireIdentifier();

        while (matchToken(","))
        {
            readType();
            requireIdentifier();
        }
    }

    requireToken(")");
}

// Functions and global variables
void globalDeclaration()
{
    readType();
    requireIdentifier();

    if (matchToken("("))
    {
        parameterList();

        if (matchToken(";"))
            return;

        codeBlock();
        return;
    }

    while (true)
    {
        if (matchToken("=") || matchToken("medalo"))
            expression();

        if (!matchToken(","))
            break;

        requireIdentifier();
    }

    requireToken(";");
}

// Conditional statement
void conditionalStatement()
{
    requireToken("agar");
    requireToken("(");
    expression();
    requireToken(")");

    codeBlock();

    if (matchToken("else"))
        codeBlock();
}

// Loop statement
void loopStatement()
{
    requireToken("jabtak");
    requireToken("(");
    expression();
    requireToken(")");

    codeBlock();
}

// Input statement
void inputStatement()
{
    requireToken("parho");
    requireIdentifier();

    while (matchToken("."))
        requireIdentifier();

    requireToken(";");
}

// Output statement
void outputStatement()
{
    requireToken("likho");
    expression();

    while (matchToken(","))
        expression();

    requireToken(";");
}

// Assignment and function-call statements
void identifierStatement()
{
    requireIdentifier();

    if (matchToken("("))
    {
        functionArguments();
        requireToken(";");
        return;
    }

    while (matchToken("."))
        requireIdentifier();

    if (!matchToken("medalo") && !matchToken("="))
        reportSyntaxError("expected an assignment operator");

    expression();
    requireToken(";");
}

// Identify and parse individual statements
void statement()
{
    if (isType())
    {
        variableDeclaration();
        return;
    }

    if (hasLexeme("agar"))
    {
        conditionalStatement();
        return;
    }

    if (hasLexeme("jabtak"))
    {
        loopStatement();
        return;
    }

    if (hasLexeme("likho"))
    {
        outputStatement();
        return;
    }

    if (hasLexeme("parho"))
    {
        inputStatement();
        return;
    }

    if (matchToken("return"))
    {
        expression();
        requireToken(";");
        return;
    }

    if (hasLexeme("shru"))
    {
        codeBlock();
        return;
    }

    if (isIdentifier())
    {
        identifierStatement();
        return;
    }

    reportSyntaxError("expected a statement");
}

// Parse a block enclosed by shru and khatam
void codeBlock()
{
    requireToken("shru");

    while (!hasLexeme("khatam"))
    {
        if (currentToken() == NULL)
            reportSyntaxError(
                "expected 'khatam' to end the block"
            );

        statement();
    }

    requireToken("khatam");
}

// Main program parser
void program()
{
    while (currentToken() != NULL)
    {
        if (hasLexeme("struct") &&
            tokenIndex + 2 < tokenList.size() &&
            tokenList[tokenIndex + 2].lexeme == "shru")
        {
            structureDeclaration();
        }
        else if (isType())
        {
            globalDeclaration();
        }
        else
        {
            reportSyntaxError(
                "expected a structure, function, or global declaration"
            );
        }
    }
}

int main(int argc, char* argv[])
{
    if (argc != 2)
    {
        cerr << "Usage: " << argv[0] << " <tokens.txt>\n";
        return 1;
    }

    if (!readTokenFile(argv[1]))
        return 1;

    program();

    cout << "Syntax is correct.\n";

    return 0;
}

